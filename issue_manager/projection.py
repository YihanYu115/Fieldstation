GENERATED = "<!-- generated by issuectl; do not edit directly -->"


def _frontmatter(data: dict[str, Any]) -> str:
    # JSON is valid YAML and keeps the generated projection dependency-free.
    return "---\n" + json.dumps(data, ensure_ascii=False, indent=2) + "\n---"


def _issue_markdown(manager: "IssueManager", issue_id: str) -> str:
    issue = manager.show_issue(issue_id)
    current = issue["current_conclusion"]
    evidence = manager.store.rows(
        "SELECT e.* FROM evidence_refs e JOIN issue_evidence ie ON ie.evidence_id=e.evidence_id "
        "WHERE ie.issue_id=? ORDER BY e.created_at",
        (issue_id,),
    )
    evidence_requests = manager.store.rows(
        "SELECT DISTINCT r.evidence_request_id,r.request_type,r.platform_id,r.state,r.priority "
        "FROM evidence_requests r LEFT JOIN issue_evidence ie ON ie.evidence_id=r.evidence_id "
        "WHERE (r.issue_id=? OR ie.issue_id=?) AND r.state IN ('pending','claimed','running') "
        "ORDER BY r.priority DESC,r.created_at",
        (issue_id, issue_id),
    )
    activity = manager.store.rows(
        "SELECT activity_sequence,activity_type,object_type,object_id,created_at "
        "FROM activity_events WHERE EXISTS (SELECT 1 FROM json_each(issue_ids_json) "
        "WHERE value=?) ORDER BY activity_sequence DESC LIMIT 20",
        (issue_id,),
    )
    questions = manager.questions.list(issue_id)
    metadata = {
        "issue_id": issue_id,
        "issue_type": issue["issue_type"],
        "parent_issue_id": issue["parent_issue_id"],
        "work_status": issue["work_status"],
        "conclusion_status": issue["conclusion_status"],
        "working_revision": issue["working_revision"],
        "conclusion_revision": issue["conclusion_revision"],
        "freshness": issue["freshness"],
        "policy_version": issue["policy_version"],
        "issue_type_registration_id": issue.get("issue_type_registration_id"),
        "issue_type_content_hash": issue.get("issue_type_content_hash"),
        "issue_type_semantic_hash": issue.get("issue_type_semantic_hash"),
    }
    lines = [GENERATED, _frontmatter(metadata), "", f"# {issue['title']}", ""]
    if current:
        lines.extend(
            [
                "## Published conclusion",
                "",
                current["statement"],
                "",
                f"- Revision: `{current['revision_number']}`",
                f"- Status: `{current['status']}`",
                f"- Confidence: `{current.get('confidence') or 'unspecified'}`",
                f"- Applicability: {current.get('applicability') or 'unspecified'}",
                f"- Change: {current.get('change_summary') or 'unspecified'}",
                "",
                "### Structured outputs",
                "",
                "```json",
                json.dumps(current["structured_outputs"], ensure_ascii=False, indent=2),
                "```",
                "",
                "### Exact basis",
                "",
            ]
        )
        if current["basis"]:
            lines.extend(
                f"- `{item['issue_id']}@r{item['conclusion_revision']}` (`{item['conclusion_id']}`)"
                for item in current["basis"]
            )
        else:
            lines.append("- None")
    else:
        lines.extend(["## Published conclusion", "", "No published conclusion."])

    lines.extend(["", "## Relations", ""])
    if issue["relations_as_consumer"]:
        for relation in issue["relations_as_consumer"]:
            lines.append(
                f"- Uses `{relation['provider_issue_id']}` via `{relation['relation_type']}` "
                f"(`{relation['impact_policy']}`)"
            )
    else:
        lines.append("- No providers")
    if issue["relations_as_provider"]:
        for relation in issue["relations_as_provider"]:
            lines.append(
                f"- Used by `{relation['consumer_issue_id']}` via `{relation['relation_type']}` "
                f"(`{relation['impact_policy']}`)"
            )

    lines.extend(["", "## Questions", ""])
    if questions:
        for question in questions:
            lines.append(
                f"- `{question['question_id']}` [{question['status']}; "
                f"{question['answer_freshness']}] {question['prompt']}"
            )
    else:
        lines.append("- None")

    lines.extend(["", "## Evidence", ""])
    if evidence:
        for item in evidence:
            source_locator = item.get("declared_source_locator") or item["locator"]
            locator_role = "declared source" if item.get("declared_source_locator") is not None else "source"
            lines.append(
                f"- `{item['evidence_id']}` [{item['kind']}] {source_locator} ({locator_role}) "
                f"(`{item.get('identity_namespace', 'legacy')}` / "
                f"`{item.get('identity_key', 'unavailable')}`; "
                f"`locator-v{item.get('locator_identity_version', 'unknown')}`) "
                f"— `{item.get('verification_level', 'declared')} + "
                f"{item.get('verification_state', 'active')}`; quality "
                f"`{item['quality_status']}`"
            )
    else:
        lines.append("- None")
    lines.extend(["", "## Pending evidence requests", ""])
    if evidence_requests:
        for item in evidence_requests:
            lines.append(
                f"- `{item['evidence_request_id']}`: `{item['request_type']}` on "
                f"`{item['platform_id']}` ({item['state']}, priority {item['priority']})"
            )
    else:
        lines.append("- None")
    lines.extend(["", "## Recent activity", ""])
    if activity:
        for item in activity:
            lines.append(
                f"- `{item['activity_sequence']}` {item['activity_type']} — "
                f"`{item['object_type']}:{item['object_id']}`"
            )
    else:
        lines.append("- None")
    lines.append("")
    return "\n".join(lines)


def _tree_lines(nodes: list[dict[str, Any]], indent: int = 0) -> list[str]:
    lines: list[str] = []
    for node in nodes:
        lines.append(
            f"{'  ' * indent}- `{node['issue_id']}` ({node['issue_type']}, r{node['conclusion_revision']}, {node['freshness']})"
        )
        lines.extend(_tree_lines(node["children"], indent + 1))
    return lines


def _mermaid(manager: "IssueManager") -> str:
    issues = manager.store.rows(
        "SELECT issue_id,title,issue_type,freshness,parent_issue_id FROM issues WHERE work_status NOT IN ('archived','void') ORDER BY issue_id"
    )
    relations = manager.store.rows(
        "SELECT consumer_issue_id,provider_issue_id,relation_type,impact_policy FROM relations WHERE active=1 ORDER BY relation_id"
    )
    safe = {row["issue_id"]: f"n{index}" for index, row in enumerate(issues)}
    lines = ["flowchart TD"]
    for row in issues:
        label = f"{row['title']}\\n[{row['issue_type']}; {row['freshness']}]".replace('"', "'")
        lines.append(f'    {safe[row["issue_id"]]}["{label}"]')
    for row in issues:
        parent = row["parent_issue_id"]
        if parent and parent in safe:
            lines.append(f"    {safe[parent]} -->|contains| {safe[row['issue_id']]}")
    for relation in relations:
        consumer = safe.get(relation["consumer_issue_id"])
        provider = safe.get(relation["provider_issue_id"])
        if not consumer or not provider:
            continue
        label = f"{relation['relation_type']}:{relation['impact_policy']}"
        arrow = (
            "-.->"
            if relation["impact_policy"] in {"soft", "notify", "none"}
            else "-->|" + label + "|"
        )
        if arrow == "-.->":
            lines.append(f"    {consumer} -. {label} .-> {provider}")
        else:
            lines.append(f"    {consumer} {arrow} {provider}")
    return "\n".join(lines) + "\n"


def _render_all(manager: "IssueManager", root: Path) -> dict[str, Any]:
    issues_dir = root / "issues"
    issues_dir.mkdir(parents=True, exist_ok=True)
    issue_ids = [
        row["issue_id"]
        for row in manager.store.rows(
            "SELECT issue_id FROM issues WHERE work_status NOT IN ('archived','void') ORDER BY issue_id"
        )
    ]
    written: list[str] = []
    for issue_id in issue_ids:
        path = issues_dir / f"{issue_id}.md"
        path.write_text(_issue_markdown(manager, issue_id), encoding="utf-8", newline="\n")
        written.append(str(path))

    tree_path = root / "tree.md"
    tree = manager.tree()
    tree_path.write_text(
        "\n".join([GENERATED, "# Issue tree", "", *_tree_lines(tree["trees"]), ""]),
        encoding="utf-8",
        newline="\n",
    )
    written.append(str(tree_path))

    stale_path = root / "stale.md"
    stale = manager.stale()
    stale_lines = [GENERATED, "# Freshness dashboard", ""]
    if stale:
        stale_lines.extend(
            f"- `{item['issue_id']}`: **{item['freshness']}** (conclusion r{item['conclusion_revision']})"
            for item in stale
        )
    else:
        stale_lines.append("All active issues are fresh.")
    stale_lines.append("")
    stale_path.write_text("\n".join(stale_lines), encoding="utf-8", newline="\n")
    written.append(str(stale_path))

    graph_path = root / "graph.mmd"
    graph_path.write_text(_mermaid(manager), encoding="utf-8", newline="\n")
    written.append(str(graph_path))

    evidence_history_path = root / "evidence-proof-history.json"
    evidence_history: dict[str, Any] = {
        "schema_version": manager.store._schema_version(manager.store.conn),
        "evidence_identities": manager.store.rows(
            "SELECT evidence_id,kind,locator,declared_source_locator,"
            "CASE WHEN declared_source_locator IS NULL THEN 'source' ELSE 'internal_identity' END AS locator_role,"
            "identity_locator,search_locator,"
            "normalized_locator,locator_identity_version,identity_namespace,identity_key "
            "FROM evidence_refs ORDER BY evidence_id"
        ),
        "identity_algorithm": "locator-v2-exact",
        "identity_migrations": manager.store.rows(
            "SELECT * FROM evidence_identity_migrations ORDER BY evidence_id"
        ),
        "identity_ambiguities": manager.store.rows(
            "SELECT * FROM evidence_identity_ambiguities ORDER BY created_at,ambiguity_id"
        ),
        "bindings": manager.store.rows(
            "SELECT * FROM evidence_source_bindings ORDER BY evidence_id"
        ),
        "binding_events": manager.store.rows(
            "SELECT * FROM evidence_source_binding_events ORDER BY created_at,binding_event_id"
        ),
        "proofs": manager.store.rows(
            "SELECT * FROM evidence_proofs ORDER BY evidence_id,semantic_revision,created_at"
        ),
        "semantic_events": manager.store.rows(
            "SELECT * FROM evidence_semantic_events ORDER BY evidence_id,created_at"
        ),
        "publication_impacts": manager.store.rows(
            "SELECT * FROM evidence_publication_impacts "
            "ORDER BY semantic_event_id,issue_id,conclusion_id"
        ),
    }
    for event in evidence_history["binding_events"]:
        event["before"] = json.loads(event.pop("before_json"))
        event["after"] = json.loads(event.pop("after_json"))
        event["review_ids"] = json.loads(event.pop("review_ids_json") or "[]")
    for ambiguity in evidence_history["identity_ambiguities"]:
        ambiguity["candidate"] = json.loads(ambiguity.pop("candidate_json") or "{}")
        ambiguity["review_ids"] = json.loads(
            ambiguity.pop("review_ids_json") or "[]"
        )
    for event in evidence_history["semantic_events"]:
        event["cause"] = json.loads(event.pop("cause_json") or "{}")
    for proof in evidence_history["proofs"]:
        proof["proof"] = json.loads(proof.pop("proof_json"))
        conversions: tuple[tuple[str, str], ...] = (
            ("source_attestation_ids_json", "source_attestation_ids"),
            ("independent_attestation_ids_json", "independent_attestation_ids"),
            ("artifact_snapshots_json", "artifact_snapshots"),
            ("analysis_run_snapshots_json", "analysis_run_snapshots"),
            ("reason_codes_json", "reason_codes"),
        )
        for source, target in conversions:
            proof[target] = json.loads(proof.pop(source) or "[]")
    evidence_history_path.write_text(
        json.dumps(evidence_history, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    written.append(str(evidence_history_path))

    registry_path = root / "registry.json"
    registry_payload = {
        "bundles": manager.registry.list_bundles(),
        "entries": manager.registry.list_entries(),
        "reference_locks": manager.store.rows(
            "SELECT * FROM registry_reference_locks "
            "ORDER BY owner_registration_id,json_pointer"
        ),
        "bindings": manager.store.rows(
            "SELECT * FROM registry_bindings ORDER BY binding_scope_type,binding_scope_id,registration_id"
        ),
    }
    registry_path.write_text(
        json.dumps(registry_payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    written.append(str(registry_path))

    v14_path = root / "v14-knowledge-workflow.json"
    v14_payload = {
        "questions": manager.store.rows(
            "SELECT * FROM issue_questions ORDER BY issue_id,priority DESC,question_id"
        ),
        "question_evidence_links": manager.store.rows(
            "SELECT * FROM issue_question_evidence_links "
            "ORDER BY question_id,evidence_id,link_type"
        ),
        "evidence_relations": manager.store.rows(
            "SELECT * FROM evidence_relations ORDER BY created_at,relation_id"
        ),
        "evidence_relation_impacts": manager.store.rows(
            "SELECT * FROM evidence_relation_impacts ORDER BY created_at,impact_id"
        ),
        "rollup_policies": manager.store.rows(
            "SELECT * FROM issue_rollup_policies ORDER BY issue_id"
        ),
        "legacy_candidates": manager.store.rows(
            "SELECT * FROM legacy_v14_candidates ORDER BY candidate_kind,created_at"
        ),
        "operation_registry": manager.operations.list(),
    }
    v14_path.write_text(
        json.dumps(v14_payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    written.append(str(v14_path))

    records_path = root / "records.json"
    records_payload = {
        "instances": manager.store.rows(
            "SELECT record_instance_id,issue_id,record_template_registration_id,created_at,"
            "created_by,current_revision_id,lifecycle_status FROM record_instances "
            "ORDER BY record_instance_id"
        ),
        "revisions": manager.store.rows(
            "SELECT record_revision_id,record_instance_id,revision_number,template_content_hash,"
            "data_json,recorded_at,recorded_by,source_mode,supersedes_revision_id,"
            "validation_profile,validation_result_json,content_hash FROM record_revisions "
            "ORDER BY record_instance_id,revision_number"
        ),
        "evidence_links": manager.store.rows(
            "SELECT * FROM record_evidence_links "
            "ORDER BY record_revision_id,field_path,evidence_id,relation_role"
        ),
        "validation_findings": manager.store.rows(
            "SELECT * FROM record_validation_findings "
            "ORDER BY record_revision_id,field_path,finding_code"
        ),
    }
    for revision in records_payload["revisions"]:
        revision["data"] = json.loads(revision.pop("data_json"))
        revision["validation_result"] = json.loads(revision.pop("validation_result_json"))
    records_path.write_text(
        json.dumps(records_payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    written.append(str(records_path))

    pipelines_path = root / "v13-proof-governance.json"
    pipelines_payload = {
        "import_jobs": manager.store.rows(
            "SELECT import_job_id,state,source_namespace,source_owner,source_system,bundle_hash,"
            "created_at,updated_at,apply_cursor FROM import_jobs ORDER BY created_at,import_job_id"
        ),
        "field_bundles": manager.store.rows(
            "SELECT field_bundle_id,bundle_version,source_namespace,source_owner,content_hash,state,"
            "base_activity_cursor,uploaded_at FROM field_bundles ORDER BY uploaded_at,field_bundle_id"
        ),
        "report_builds": manager.store.rows(
            "SELECT report_build_id,report_template_registration_id,report_template_content_hash,"
            "renderer_name,renderer_version,renderer_hash,report_model_hash,basis_hash,state,"
            "output_format,normalized_scope_hash,renderer_kind,renderer_registration_id,"
            "adapter_name,adapter_version,adapter_executable_hash,adapter_descriptor_hash,"
            "renderer_config_hash,adapter_limits_json,adapter_limits_hash,output_media_type,"
            "output_extension,output_artifact_id,"
            "output_hash,prepared_at,built_at FROM report_builds "
            "ORDER BY prepared_at,report_build_id"
        ),
        "field_bundle_attachments": manager.store.rows(
            "SELECT field_bundle_id,attachment_path,expected_sha256,expected_size,mime_type,"
            "artifact_id,upload_state,received_bytes,verified_at "
            "FROM field_bundle_attachments ORDER BY field_bundle_id,attachment_path"
        ),
        "field_bundle_event_actions": manager.store.rows(
            "SELECT * FROM field_bundle_event_actions "
            "ORDER BY field_bundle_event_id,action_index"
        ),
        "integration_conflicts": manager.store.rows(
            "SELECT * FROM integration_conflicts "
            "ORDER BY detected_at,integration_conflict_id"
        ),
        "integration_conflict_resolutions": manager.store.rows(
            "SELECT * FROM integration_conflict_resolutions "
            "ORDER BY integration_conflict_id,to_revision"
        ),
        "import_manifest_candidates": [
            {
                **{key: value for key, value in candidate.items() if key != "candidate_json"},
                "candidate": json.loads(candidate["candidate_json"]),
            }
            for candidate in manager.store.rows(
                "SELECT * FROM import_manifest_candidates "
                "ORDER BY import_job_id,created_at,import_manifest_candidate_id"
            )
        ],
        "adapters": manager.adapters.list(),
        "migration_findings": manager.store.rows(
            "SELECT * FROM migration_findings ORDER BY migration_version,finding_id"
        ),
        "migration_resolution_attempts": manager.store.rows(
            "SELECT * FROM migration_finding_resolution_attempts "
            "ORDER BY created_at,attempt_id"
        ),
        "migration_resolution_receipts": manager.store.rows(
            "SELECT * FROM migration_finding_resolution_receipts "
            "ORDER BY resolved_at,receipt_id"
        ),
        "migration_resolution_dependencies": manager.store.rows(
            "SELECT * FROM migration_resolution_dependencies "
            "ORDER BY receipt_id,ordinal"
        ),
        "migration_resolution_replays": manager.store.rows(
            "SELECT * FROM migration_resolution_replays "
            "ORDER BY replayed_at,replay_id"
        ),
        "migration_policy_repairs": manager.store.rows(
            "SELECT * FROM migration_policy_repairs ORDER BY created_at,repair_id"
        ),
        "integrity_quarantines": manager.store.rows(
            "SELECT * FROM integrity_quarantines ORDER BY created_at,quarantine_id"
        ),
        "governed_conflict_resolution_receipts": manager.store.rows(
            "SELECT * FROM governed_conflict_resolution_receipts "
            "ORDER BY applied_at,receipt_id"
        ),
        "readiness": {
            "implementation": __version__,
            "schema_version": manager.store._schema_version(manager.store.conn),
            "ci_verified": False,
            "migration_rehearsed": False,
            "shadow_pilot_signed": False,
            "production_released": False,
        },
    }
    pipelines_path.write_text(
        json.dumps(pipelines_payload, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
        newline="\n",
    )
    written.append(str(pipelines_path))

    return {"export_root": str(root), "files": written, "issue_count": len(issue_ids)}


def export_all(manager: "IssueManager") -> dict[str, Any]:
    final_root = manager.store.ledger_dir / "exports"
    temporary = Path(tempfile.mkdtemp(prefix=".exports-", dir=manager.store.ledger_dir))
    previous = manager.store.ledger_dir / ".exports-previous"
    try:
        result = _render_all(manager, temporary)
        if previous.exists():
            shutil.rmtree(previous)
        if final_root.exists():
            final_root.replace(previous)
        temporary.replace(final_root)
        if previous.exists():
            shutil.rmtree(previous)
    except Exception:
        if not final_root.exists() and previous.exists():
            previous.replace(final_root)
        if temporary.exists():
            shutil.rmtree(temporary)
        raise
    files = [
        str(final_root / Path(path).relative_to(result["export_root"])) for path in result["files"]
    ]
    return {"export_root": str(final_root), "files": files, "issue_count": result["issue_count"]}
